#[test]
fn conductor_settings_toml() {
    let i = conductor(
        r#""$schema" = "https://conductor.build/schemas/settings.repo.schema.json"
[scripts]
setup = """
pnpm install
cp "$CONDUCTOR_ROOT_PATH/.env" .env
"""
archive = "./script/workspace-archive.sh"
run_mode = "nonconcurrent"
[scripts.run.web]
command = "pnpm dev --port $CONDUCTOR_PORT"
default = true
[scripts.run.api]
command = "pnpm api"
args = ["--port", "$((CONDUCTOR_PORT + 1))"]
options = { cwd = "server" }
available_in = ["local"]
[scripts.run.deploy]
command = "make deploy"
available_in = "cloud"
[environment_variables]
NODE_ENV = "development"
"#,
    )
    .unwrap();
    let s = &i.scripts;
    assert!(s.setup.as_deref().unwrap().starts_with("export NODE_ENV=development\npnpm install"));
    assert_eq!(
        s.archive.as_deref(),
        Some("export NODE_ENV=development\n./script/workspace-archive.sh")
    );
    assert_eq!(s.run_mode, RunMode::Exclusive);
    assert!(s.run["web"].default);
    assert_eq!(
        s.run["api"].command,
        "export NODE_ENV=development\ncd server && pnpm api --port '$((CONDUCTOR_PORT + 1))'"
    );
    assert!(!s.run.contains_key("deploy"), "cloud-only scripts are skipped");
    assert!(i.notes[0].contains("cloud-only"));
    // The legacy string form.
    let i = conductor("[scripts]\nrun = \"npm start\"\n").unwrap();
    assert_eq!(i.scripts.run["run"].command, "npm start");
    let j = conductor_json(r#"{"scripts":{"setup":"npm ci","run":"npm start","archive":""},"runScriptMode":"nonconcurrent"}"#).unwrap();
    assert_eq!((j.scripts.setup.as_deref(), j.scripts.archive.as_deref()), (Some("npm ci"), None));
    assert_eq!(j.scripts.run_mode, RunMode::Exclusive);
}

#[test]
fn superset_config_with_local_layer_and_script_fallback() {
    let dir = tempfile::tempdir().unwrap();
    std::fs::create_dir(dir.path().join(".superset")).unwrap();
    std::fs::write(dir.path().join(".superset/teardown.sh"), "#!/bin/sh\n").unwrap();
    std::fs::write(
        dir.path().join(".superset/config.local.json"),
        r#"{"setup": {"before": ["echo hi"], "after": ["echo bye"]}}"#,
    )
    .unwrap();
    let i = superset(
        dir.path(),
        r#"{ "setup": ["bun install", "./.superset/setup.sh"], "run": ["bun dev"] }"#,
    )
    .unwrap();
    assert_eq!(
        i.scripts.setup.as_deref(),
        Some("set -e\necho hi\nbun install\n./.superset/setup.sh\necho bye")
    );
    assert_eq!(
        i.scripts.archive.as_deref(),
        Some("set -e\n./.superset/teardown.sh"),
        "falls back to <key>.sh"
    );
    assert_eq!(i.scripts.run["run"].command, "set -e\nbun dev");
    let e = superset(dir.path(), r#"{ "setup": "bun install" }"#).unwrap_err();
    assert!(e.contains("array"), "{e}");
}

#[test]
fn codex_environment_toml() {
    let i = codex(
        r#"# THIS IS AUTOGENERATED. DO NOT EDIT MANUALLY
version = 1
name = "my-app"
[setup]
script = '''
set -eu
pnpm install
'''
[setup.win32]
script = "pnpm.cmd install"
[cleanup]
script = "docker compose down"
[[actions]]
name = "Test"
icon = "test"
command = "pnpm test"
[[actions]]
name = "Run"
icon = "run"
command = "pnpm dev"
"#,
    )
    .unwrap();
    assert_eq!(i.scripts.setup.as_deref(), Some("set -eu\npnpm install\n"));
    assert_eq!(i.scripts.archive.as_deref(), Some("docker compose down"));
    assert!(i.scripts.run["run"].default && !i.scripts.run["test"].default);
}

#[test]
fn claude_launch_json_ports_follow_the_worktree() {
    let i = claude_launch(
        r#"{ "version": "0.0.1",
  // comments are allowed
  "configurations": [
    { "name": "frontend", "runtimeExecutable": "npm", "runtimeArgs": ["run","dev","--","--port","3000"],
      "cwd": "apps/web", "port": 3000, "autoPort": true },
    { "name": "api", "program": "server.js", "args": ["-p", "8080"], "env": {"NODE_ENV":"development"} },
    { "name": "oauth", "runtimeExecutable": "npm", "runtimeArgs": ["start"], "port": 4000, "autoPort": false },
    { "name": "remote", "url": "http://localhost:9000" } ] }"#,
    )
    .unwrap();
    let r = &i.scripts.run;
    assert_eq!(
        r["frontend"].command,
        "cd apps/web && PORT=\"$PTYRO_PORT\" npm run dev -- --port \"$PTYRO_PORT\""
    );
    assert!(r["frontend"].default);
    assert_eq!(
        r["api"].command,
        "export NODE_ENV=development\nPORT=\"$((PTYRO_PORT + 1))\" node server.js -p \"$((PTYRO_PORT + 1))\""
    );
    assert_eq!(r["oauth"].command, "npm start");
    assert!(!r.contains_key("remote"));
    assert_eq!(i.notes.len(), 2, "{:?}", i.notes);
}

#[test]
fn cursor_environment_json() {
    let i = cursor(
        r#"{
  "build": { "dockerfile": "Dockerfile", "context": ".." },
  "install": "pnpm install",
  "start": "sudo service docker start",
  "terminals": [
    { "name": "web", "command": "pnpm dev", "description": "Next.js" },
    [ { "name": "worker", "command": "pnpm worker" } ]
  ],
  "ports": [{ "port": 3000, "name": "web" }]
}"#,
    )
    .unwrap();
    assert_eq!(i.scripts.setup.as_deref(), Some("pnpm install"));
    assert_eq!(i.scripts.run["start"].command, "sudo service docker start");
    assert!(i.scripts.run["web"].default);
    assert_eq!(i.scripts.run["worker"].command, "pnpm worker");
    assert_eq!(i.notes.len(), 1);
}

#[test]
fn copilot_setup_steps_keep_run_steps_only() {
    let i = copilot(
        r#"name: "Copilot Setup Steps"
on:
  workflow_dispatch:
jobs:
  copilot-setup-steps:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v6
      - uses: actions/setup-node@v7
        with: { node-version: "20", cache: npm }
      - name: Install JS dependencies
        run: npm ci
      - name: Secret thing
        run: echo ${{ secrets.TOKEN }}
      - name: Build
        working-directory: packages/core
        run: |
          npm run build
          npx playwright install --with-deps
"#,
    )
    .unwrap();
    assert_eq!(
        i.scripts.setup.as_deref(),
        Some(
            "set -e\n# Install JS dependencies\nnpm ci\n# Build\n(cd packages/core && npm run build\nnpx playwright install --with-deps)"
        )
    );
    assert_eq!(i.notes.len(), 2, "{:?}", i.notes);
    assert!(copilot("jobs:\n  build:\n    steps: []\n").is_err());
}

#[test]
fn json_comments_are_stripped_outside_strings() {
    let t = strip_json_comments("{\"a\": \"http://x\", // c\n /* b */ \"b\": \"/* not */\"}");
    let v: Value = serde_json::from_str(&t).unwrap();
    assert_eq!((v["a"].as_str(), v["b"].as_str()), (Some("http://x"), Some("/* not */")));
}

#[test]
fn discover_orders_and_skips_the_legacy_conductor_file() {
    let dir = tempfile::tempdir().unwrap();
    let d = dir.path();
    std::fs::create_dir_all(d.join(".conductor")).unwrap();
    std::fs::write(d.join(".conductor/settings.toml"), "[scripts]\nsetup = \"a\"\n").unwrap();
    std::fs::write(d.join("conductor.json"), r#"{"scripts":{"setup":"legacy"}}"#).unwrap();
    std::fs::create_dir_all(d.join(".cursor")).unwrap();
    std::fs::write(d.join(".cursor/environment.json"), r#"{"install": "b"}"#).unwrap();
    std::fs::create_dir_all(d.join(".codex/environments")).unwrap();
    std::fs::write(d.join(".codex/environments/default.toml"), "[setup]\nscript = \"c\"\n")
        .unwrap();
    let found = discover(d);
    let files: Vec<&str> = found.iter().map(|i| i.file.as_str()).collect();
    assert_eq!(
        files,
        [
            ".conductor/settings.toml",
            ".codex/environments/default.toml",
            ".cursor/environment.json"
        ]
    );
}
